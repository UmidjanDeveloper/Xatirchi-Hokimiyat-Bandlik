--
--  Оффлайн навбат хатловни қайта-қайта юборади. Сервер эса
--  409 нинг иккита ҳар хил сабабини ажрата олмасди:
--
--    · ўзимизнинг олдинги юборишимиз аллақачон ўтган;
--    · ҳамкасб ўша хонадонни аввалроқ киритган.
--
--  Иккиси ҳам «такрор» деб ҳисобланар ва ёзув телефон
--  навбатидан ЎЧИРИЛАРДИ. Иккинчи ҳолатда бу ходимнинг бир
--  соатлик ишини йўқотиш эди.
--
--  Устун NULL бўлиши мумкин: мавжуд ёзувларда калит йўқ ва
--  PostgreSQL'да UNIQUE индекс бир нечта NULL га рухсат
--  беради.
-- ============================================================
ALTER TABLE "Household" ADD COLUMN IF NOT EXISTS "idempotentlikKaliti" TEXT;

CREATE UNIQUE INDEX IF NOT EXISTS "Household_idempotentlikKaliti_key"
  ON "Household"("idempotentlikKaliti");
