--
--  Такрорни аввал ФАҚАТ код текширарди ва у иккита ҳолда
--  ишламасди:
--
--    · битта файлда бир одам икки сатрда турса — текширув
--      сикл бошида бир марта бўларди ва иккала сатр ҳам
--      далил яратарди;
--
--    · иккита администратор файлни бир вақтда юкласа —
--      иккови ҳам «йўқ экан» деб кўрарди.
--
--  ── НЕГА ШАРТЛИ ──
--
--  Хатлов ҲОЗИР кетмоқда. Агар базада эски такрорлар бўлса,
--  оддий `CREATE UNIQUE INDEX` МИГРАЦИЯНИ ЙИҚИТАДИ ва деплой
--  тўхтайди — ходимлар эса дала телефонида қолади.
--
--  Уларни ўчириб юбориш ҳам мумкин эмас: ўчирилган далил
--  «тасдиқланган жойлаштириш» рақамини ўзгартиради, миграция
--  эса маълумотни САҚЛАШИ керак.
--
--  Шунинг учун: такрор бўлмаса — чегара қўйилади; бўлса —
--  қўйилмайди ва база огоҳлантириш ёзади. Код даражасидаги
--  ҳимоя иккала ҳолда ҳам ишлайверади.
--
--  Қолган такрорларни администратор кўриб, ўзи ҳал қилади —
--  кейин миграцияни қайта юргизиш кифоя.
--
--  Бу миграция ҲЕЧ НАРСА ЎЧИРМАЙДИ ва ҳеч нарсани
--  ўзгартирмайди.
-- ============================================================
DO $$
DECLARE
  takrorlar INTEGER;
BEGIN
  SELECT COUNT(*) INTO takrorlar FROM (
    SELECT "ishsizId", turi, "reyestrSanasi"
    FROM "JoylashuvDalili"
    WHERE "reyestrSanasi" IS NOT NULL
    GROUP BY "ishsizId", turi, "reyestrSanasi"
    HAVING COUNT(*) > 1
  ) t;

  IF takrorlar = 0 THEN
    CREATE UNIQUE INDEX IF NOT EXISTS "dalil_takrori"
      ON "JoylashuvDalili"("ishsizId", "turi", "reyestrSanasi");
  ELSE
    RAISE NOTICE 'dalil_takrori indeksi QO''YILMADI: bazada % ta takror guruh bor. Ularni ko''rib chiqing va migratsiyani qayta yurgizing.', takrorlar;
  END IF;
END $$;
