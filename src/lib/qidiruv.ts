/**
 * ============================================================
 *  НОМ БЎЙИЧА ҚИДИРУВ — иккала алифбода
 *
 *  Маҳалла номлари базада КИРИЛЛда сақланади, экранда эса
 *  фойдаланувчи танлаган алифбода кўринади. Қидирув эса
 *  иккаласида ҳам ишлаши керак: кириллда очиб турган одам
 *  «uysh» деб ёзиши мумкин — ва тўғри қилади, чунки у
 *  клавиатурасини алмаштириб ўтирмайди.
 *
 *  Апостроф эътиборга олинмайди: «Боғчакалон» ни лотинда ёзган
 *  одам «Bog'chakalon» эмас, «bogchakalon» деб теради.
 *
 *  Шу қоида иккита жойда керак — харитадаги рўйхатда ва
 *  панелдаги МФЙ танловида — шунинг учун битта файлда туради.
 *  Иккита нусха бўлганда бири тузалиб, иккинчиси эскирарди.
 * ============================================================
 */
import { lotinga } from '@/lib/alifbo';

/** Қидирув учун соддалаштирилган ном */
export const qidiruvKaliti = (nom: string): string =>
  nom.toLowerCase().replace(/[''ʻʼ`´]/g, '');

/**
 * Кириллча ном сўровга мос келадими.
 *
 * Сўров бўш бўлса ҲАММАСИ мос келади — рўйхат тўла кўринади.
 */
export function nomMos(nomiKirill: string, sorov: string): boolean {
  const s = qidiruvKaliti(sorov.trim());
  if (!s) return true;
  return (
    qidiruvKaliti(nomiKirill).includes(s) ||
    qidiruvKaliti(lotinga(nomiKirill)).includes(s)
  );
}
