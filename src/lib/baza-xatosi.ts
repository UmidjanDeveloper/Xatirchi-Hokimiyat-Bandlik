/**
 * Танилган база хатоси бўлса — ўзбекча изоҳ, акс ҳолда `null`.
 *
 * `null` қайтса, чақирувчи умумий хабар беради ва хатони
 * журналга ёзади.
 */
export function bazaXatosi(e: unknown): string | null {
  if (!(e instanceof Prisma.PrismaClientKnownRequestError)) return null;

  switch (e.code) {
    /* P2021 — жадвал йўқ, P2022 — устун йўқ */
    case 'P2021':
    case 'P2022':
      return (
        'Базанинг тузилиши кодга мос эмас: янги версия чиққан, аммо базага ўзгариш қўлланмаган. ' +
        'Администратор «Бошқарув» саҳифасидаги «Тизим ҳолати» блокидан текширсин — у қандай тузатишни ёзиб беради.'
      );

    /* Уланиб бўлмади */
    case 'P1001':
    case 'P1002':
      return 'Маълумотлар базасига уланиб бўлмади. Бир дақиқадан сўнг қайта уриниб кўринг; такрорланса — администраторга айтинг.';

    /* Уланишлар чегараси тўлган — пулерсиз ишлаганда учрайди */
    case 'P2024':
      return 'Базага уланишлар чегараси тўлган. Бир дақиқадан сўнг қайта уриниб кўринг.';

    default:
      return null;
  }
}

/**
 * Базада ҳақиқатан устун/жадвал етишмаяптими.
 *
 * Тизим ҳолати блоки шу белгига қараб «миграция қўлланмаган»
 * деб хулоса чиқаради.
 */
export function tuzilishXatosimi(e: unknown): boolean {
  return (
    e instanceof Prisma.PrismaClientKnownRequestError &&
    (e.code === 'P2021' || e.code === 'P2022')
  );
}
