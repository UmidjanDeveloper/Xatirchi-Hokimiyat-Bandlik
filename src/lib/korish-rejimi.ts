/** Ўзгартирмайдиган — кўриш режимида рухсат этилган усуллар */
export const OQISH_USULLARI = ['GET', 'HEAD', 'OPTIONS'] as const;

/**
 * Кўриш режимида ҳам ишлаши ШАРТ бўлган йўллар.
 *
 * Иккови ҳам POST/DELETE, лекин уларсиз одам қулф ичида
 * қолиб кетарди: биринчиси кўз режимидан чиқаради,
 * иккинчиси умуман тизимдан.
 */
export const KORISH_ISTISNOLARI = ['/api/admin/korish', '/api/auth/chiqish'] as const;

/** Миддлевар ҳар сўровга қўядиган сарлавҳа — усулни ичкарига олиб киради */
export const USUL_SARLAVHASI = 'x-sorov-usuli';

export function ozgartirishmi(usul: string | null | undefined): boolean {
  if (!usul) return false;
  return !(OQISH_USULLARI as readonly string[]).includes(usul.toUpperCase());
}

export function istisnomi(yol: string): boolean {
  return KORISH_ISTISNOLARI.some((y) => yol === y || yol.startsWith(`${y}/`));
}

/**
 * Кўриш режимида ҲАМ ишлайдиган, лекин ЁЗМАЙДИГАН POST йўллари —
 * Ҳамроҳ билан савол-жавоб.
 *
 * ── Нега улар POST ──
 *
 * Савол матни ва овоз тананинг ичида келади, уни манзилга қўйиб
 * бўлмайди. Бу йўллар ходимнинг ҳеч бир маълумотини ўзгартирмайди.
 * Ёзадиган ягона нарса — фойдаланиш ҳисоби ва тезлик чегараси, у эса
 * нишон ходимники эмас, АДМИНИСТРАТОРнинг ўз `userId`си бўйича
 * юритилади (`talabQil` сессиядаги ҳақиқий ҳисобни қайтаради).
 *
 * ── Нега `/api/agent/tasdiq` бу ерда ЙЎҚ ──
 *
 * У ёзиш амалини БАЖАРАДИ. Кўриш режимида у ҳамон тўсилади, Коаланинг
 * ўзи эса бу режимда ёзиш амалини умуман таклиф қилмайди
 * (`AgentKontekst.oqishFaqat`).
 *
 * ── Икки калит ──
 *
 * Рўйхат ИККИ жойда икки хил калит билан ишлайди: миддлевар (шу
 * рўйхат) ва йўлнинг ўзи (`talabQil(..., { korishdaOqish: true })`).
 * Биттаси унутилса — ёзиш тўсилаверади. Йўл ТЎЛИҚ мос келиши шарт:
 * `startsWith` ишлатилмайди, шунда кейинчалик қўшилган ички йўллар
 * ўз-ўзидан очилиб қолмайди.
 */
export const KORISH_OQISH_POSTLARI = [
  '/api/agent/suhbat',
  '/api/agent/ovoz',
  '/api/agent/gapir',
  '/api/agent/jonli',
] as const;

export function korishdaOqishmi(yol: string): boolean {
  return (KORISH_OQISH_POSTLARI as readonly string[]).includes(yol);
}

/**
 * Сессияда «кўз» борми — нишон ходим ҳозир фаолми-йўқми, фарқсиз.
 *
 * `talabQil` нишон ўчирилган бўлса `korish` ни бермайди ва одам ўз
 * ролида қолади, миддлевар эса cookie'даги «кўз» туфайли ҳамон ёзишни
 * тўсиб туради. Шу оралиқ ҳолатда ҳам Коала ЁЗИШ таклиф қилмаслиги учун
 * қарор cookie'даги «кўз»га қараб олинади.
 */
export function korishdami(sessiya: { userId: string; koz?: string | null }): boolean {
  return Boolean(sessiya.koz) && sessiya.koz !== sessiya.userId;
}

/**
 * Сессия токенидан «кўз» ни ИМЗОНИ ТЕКШИРМАСДАН ўқийди.
 *
 * ── Нега имзосиз ўқиш хавфсиз ──
 *
 * Бу функция ФАҚАТ ЧЕКЛАШ учун ишлатилади: «кўз» топилса,
 * ёзиш тўсилади. Яъни энг ёмон ҳолатда ҳужумчи ўзини
 * ўзи чеклайди.
 *
 * Тескари йўналиш эса ёпиқ: «кўз» ни олиб ташлаш учун
 * токенни қайта имзолаш керак, калит эса серверда.
 * Имзоси бузилган токенни `talabQil()` умуман рад этади.
 *
 * Миддлевар Edge муҳитида ишлайди ва у ерда Node'нинг
 * `crypto.timingSafeEqual` и йўқ — шунинг учун имзо
 * ўша ерда текширилмайди.
 */
export function kozniOqi(token?: string | null): string | null {
  if (!token) return null;
  const payload = token.split('.')[0];
  if (!payload) return null;
  try {
    const b64 = payload.replace(/-/g, '+').replace(/_/g, '/');
    const matn = atob(b64.padEnd(Math.ceil(b64.length / 4) * 4, '='));
    const data = JSON.parse(matn) as { koz?: unknown };
    return typeof data.koz === 'string' && data.koz ? data.koz : null;
  } catch {
    return null;
  }
}
