import {
  OLCHOVLAR,
  malumotBormi,
  type Olchov,
  type OlchovKaliti,
} from '@/components/xarita/olchovlar';
import type { XaritaQatori } from '@/lib/xarita/xarita-malumoti';

/**
 * ============================================================
 *  ТАБЛОДА ҚАЙСИ ЎЛЧОВЛАР АЙЛАНАДИ
 *
 *  ── Нега ҳаммаси эмас ──
 *
 *  Етти ўлчовнинг ҳаммаси айлантирилса, табло ярим вақтини
 *  БЎШ харита кўрсатиб ўтказарди: бугун «ишга жойлаштириш»
 *  кесимида фақат иккита МФЙ да рақам бор, қолган 68 таси
 *  кулранг.
 *
 *  Йўлакдан ўтаётган одам ўша лаҳзада қараса, у тизимни
 *  «ишламаяпти» деб ўқийди. Аслида ишламаётган нарса йўқ —
 *  шунчаки ўша кесимда ҳали маълумот йиғилмаган.
 *
 *  Шунинг учун ўлчов ФАҚАТ гапирадиган нарсаси бўлганда
 *  қаторга киради. Хатлов ёйилгани сари улар ўзи қўшилиб
 *  боради — ҳеч ким ҳеч нарсани қўлда ёқмайди.
 * ============================================================
 */

/**
 * Айланиш тартиби.
 *
 * Аввал ИШ кесимлари (қамров, натижа, қолдиқ), охирида база.
 * База ўлчови ҳар доим тўла ва ҳар доим кўрсатилади — у
 * «қаерда ишсиз кўп» деган саволга хатловдан олдин ҳам жавоб
 * беради, шунинг учун табло ҳеч қачон бўш қолмайди.
 */
const TARTIB: OlchovKaliti[] = ['qamrov', 'natija', 'ishsiz', 'bazaIshsiz'];

/**
 * Ўлчов қаторга кириши учун камида нечта МФЙ да рақам бўлиши
 * керак.
 *
 * Иккита МФЙ билан харита тузилмайди: чораклар ҳам, «энг
 * юқори учтаси» ҳам маъносиз бўлиб қолади.
 */
export const KAMIDA_MALUMOT = 3;

export function tabloOlchovlari(qatorlar: XaritaQatori[]): Olchov[] {
  const natija: Olchov[] = [];

  for (const kalit of TARTIB) {
    const olchov = OLCHOVLAR.find((o) => o.kalit === kalit);
    if (!olchov) continue;

    if (olchov.bazaviy) {
      natija.push(olchov);
      continue;
    }

    /*
     * «Маълумот бор» етмайди — қиймат ҳам бўлиши керак.
     *
     * Хатлов бошланган, аммо биронта фуқаро ишга жойлашмаган
     * маҳалла «натижа» кесимида маълумотли ҳисобланади, ва
     * қиймати нол. Ўттизта ноль билан харита барибир бўш
     * кўринади.
     */
    const gapiradigan = qatorlar.filter(
      (q) => malumotBormi(q, olchov) && (olchov.foiz(q) ?? olchov.hajm(q)) > 0
    ).length;

    if (gapiradigan >= KAMIDA_MALUMOT) natija.push(olchov);
  }

  /* База ўлчови ҳар доим рўйхатда — бу ерга тушмаслиги керак */
  return natija.length > 0 ? natija : OLCHOVLAR.slice(0, 1);
}
