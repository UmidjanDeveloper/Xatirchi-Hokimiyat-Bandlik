import { prisma } from '@/lib/prisma';
import { joriySessiya } from '@/lib/auth';
import { HisobotTugmalari } from './hisobot-tugmalari';

/**
 * ============================================================
 *  САҲИФА ҲИСОБОТИ — ҳар панелдаги PDF/Excel тугмалари
 *
 *  Илгари тугмалар фақат учта саҳифада бор эди: хатлов, таҳлил
 *  панели ва операцион панел. Қолганларида — ишсизлар,
 *  хонадонлар, чора-тадбирлар, бўш иш ўринлари, бошқарув —
 *  йўқ эди.
 *
 *  Амалда бу шуни англатарди: ходим чора-тадбирлар рўйхатини
 *  очиб туриб, уни ҳужжат қилиш учун бошқа саҳифага ўтиши
 *  керак эди. Ҳоким эса — унинг менюсида фақат иккита банд
 *  бор — чора-тадбирлар саҳифасидан ҳисобот ололмасди.
 *
 *  ── Нега алоҳида компонент ──
 *
 *  Тугмаларнинг ўзи бир хил, аммо ПРОПЛАРИ ролга боғлиқ:
 *  маҳалла ходимига «бутун туман» тушунчаси керак эмас ва
 *  унга ҳудуд танлаш рўйхати ҳам кўрсатилмайди — у барибир
 *  фақат ўз маҳалласини кўради. Бу мантиқни бешта саҳифага
 *  кўчириб ёзсак, эртага биттаси ўзгартирилмай қолиб кетарди
 *  ва иккита саҳифа ҳар хил ишларди.
 *
 *  ── Ҳисобот БИТТА ва ТЎЛИҚ ──
 *
 *  Қайси саҳифадан босилмасин, файл бир хил чиқади: хатлов,
 *  фуқаролар, чора-тадбирлар, бўш ўринлар, диаграммалар ва
 *  хулоса. Ҳар саҳифа ўз «қисқа» ҳисоботини берса, йиғилишда
 *  икки киши икки хил рақам билан келарди.
 * ============================================================
 */
export async function SahifaHisoboti({
  malumotBormi = true,
}: {
  /** Маълумот борми — йўқ бўлса тугма босилмайди, аммо кўринади */
  malumotBormi?: boolean;
}) {
  const sessiya = joriySessiya();
  if (!sessiya) return null;

  const ozMahallasi = sessiya.rol === 'YETTILIK';

  /*
   * Ҳудуд танлаш рўйхати фақат туман даражасидаги роллар учун.
   * Маҳалла ходимига рўйхат кўрсатилса, у бошқа маҳаллани
   * танлаб, бўш ҳисобот олиб «ишламаяпти» деб ўйларди.
   */
  const mahallalar = ozMahallasi
    ? undefined
    : await prisma.mahalla.findMany({
        orderBy: { nomi: 'asc' },
        select: { id: true, nomiKirill: true },
      });

  return (
    <HisobotTugmalari
      qamrov={{ nomi: ozMahallasi ? '' : 'Хатирчи тумани' }}
      mahallalar={mahallalar}
      ozMahallasi={ozMahallasi}
      malumotBormi={malumotBormi}
    />
  );
}
