/**
 * ============================================================
 *  АНДОЗАНИ КОДГА АЙЛАНТИРИШ
 *
 *  Ҳокимлик юборган `.xlsx` файлини base64 сатрга ўгириб,
 *  `src/lib/hisobot/andoza/andoza-fayli.ts` га ёзади.
 *
 *  ── Нега файлдан ЎҚИЛМАЙДИ ──
 *
 *  Аввалги вариантда андоза дискдан ўқиларди
 *  (`readFile(process.cwd() + ...)`). Маҳаллий машинада
 *  ишларди, аммо Vercel да серверсиз функцияга қайси файл
 *  тушишини Next.js ўзи ҳал қилади ва кодда ёзилмаган файл
 *  умуман тушмаслиги мумкин. Уни созлама билан мажбурлаш
 *  мумкин эди, лекин бу ерда синаб кўриб бўлмайди — ва
 *  синалмаган созлама ишлаб турган сайтни бузиб қўйди.
 *
 *  Base64 сатр эса КОДНИНГ ЎЗИ: бандлер уни ҳар доим олиб
 *  кетади, ҳеч қандай созлама талаб қилмайди ва ҳеч қачон
 *  «файл топилмади» бермайди. 34 КБ файл 46 КБ сатрга
 *  айланади — буни кўтариш арзон.
 *
 *  ── Ҳокимлик янги андоза юборса ──
 *
 *    1. эски файл ўрнига янгисини қўйинг:
 *       src/lib/hisobot/andoza/mahalla-jadvali.xlsx
 *    2. `npm run andoza` ни ишга туширинг;
 *    3. `npm run sinov` — устун сонлари ўзгарган бўлса
 *       синов дарҳол айтади.
 * ============================================================
 */
import { readFileSync, writeFileSync } from 'node:fs';

const MANBA = 'src/lib/hisobot/andoza/mahalla-jadvali.xlsx';
const MAQSAD = 'src/lib/hisobot/andoza/andoza-fayli.ts';

const bayt = readFileSync(MANBA);
const b64 = bayt.toString('base64');

/* Узун сатрни 96 белгилик бўлакларга ажратамиз — таҳрирловчи қотиб қолмасин */
const boleklar = (b64.match(/.{1,96}/g) ?? []).map((x) => `  '${x}',`).join('\n');

writeFileSync(
  MAQSAD,
  `/**
 * ============================================================
 *  ҲОКИМЛИК ЖАДВАЛИ АНДОЗАСИ — base64 да
 *
 *  БУ ФАЙЛ ҚЎЛДА ТАҲРИРЛАНМАЙДИ.
 *
 *  У \`${MANBA}\`
 *  дан \`npm run andoza\` билан ҳосил қилинади.
 *
 *  Нега кодда: серверсиз функцияга дискдаги файл тушмаслиги
 *  мумкин, base64 сатр эса коднинг ўзи — бандлер уни ҳар
 *  доим олиб кетади.
 *
 *  Манба ўлчами: ${bayt.length} байт
 * ============================================================
 */

const BOLAKLAR: string[] = [
${boleklar}
];

/** Андозанинг хом байтлари */
export const ANDOZA_BAYTI = Buffer.from(BOLAKLAR.join(''), 'base64');
`,
  'utf8'
);

console.log(`${MANBA} -> ${MAQSAD}`);
console.log(`  ${bayt.length} bayt -> ${b64.length} belgi`);
